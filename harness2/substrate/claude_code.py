"""ClaudeCodeSubstrate: Claude Code (headless `claude -p`) as a solver substrate.

The canonical c1..c4 filenames are kept, so a tree moves between substrates unchanged; only
`materialise` translates it into what Claude Code loads:

    systemprompt.md, guardrails.md,          -> .claude/harness/<same path>, pulled into
    LongTermMEMORY.md,                          context by a generated CLAUDE.md made of
    tool_descriptions/tool_guidance.md          `@` imports (Claude Code's memory import syntax)
    .claude/skills/<n>/SKILL.md (+scripts/)  -> unchanged (Claude Code's skill directory)
    sub_agents/<n>/AGENT.md                  -> .claude/agents/<n>.md, `name: <n>` ensured
    scripts/<name>.py                        -> unchanged, run from the workspace root
    .claude/settings.json (hooks)            -> unchanged; c8 is Claude Code's hooks

Always-on files are injected verbatim and never templated, so LaTeX braces are safe in them.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Mapping

from ..core import runmark as RM
from ..core import tree as HT
from ..core.tree import SurfaceSpec
from .base import Install, Launcher, RunRequest

CLAUDE_CODE_SURFACE = SurfaceSpec(
    name="claude_code",
    always_on=(
        "systemprompt.md",
        "guardrails.md",
        "LongTermMEMORY.md",
        "tool_descriptions/tool_guidance.md",
    ),
    always_on_max=24_000,
    always_on_cap_reason=(
        "CLAUDE.md and every file it imports are loaded into the context of every turn"
    ),
    skill_dir=".claude/skills",
    skill_name_rule="must_match",
    trigger_hint=(
        "Fix it by adding a trigger line naming `{name}` to systemprompt.md or "
        'guardrails.md, e.g. "When <the situation this skill handles>, use the '
        '`{name}` skill."'
    ),
    autotrigger_file="guardrails.md",
    trigger_line="- When {desc}, use the `{name}` skill.\n",
    subagent_requires_mode=False,
    plugin_dir=None,
    hooks_file=".claude/settings.json",
    hook_events=frozenset(
        {
            "PreToolUse",
            "PostToolUse",
            "Notification",
            "UserPromptSubmit",
            "Stop",
            "SubagentStop",
            "PreCompact",
            "SessionStart",
            "SessionEnd",
        }
    ),
    compile_skill_scripts=True,
    stubs=(
        (
            "scripts/README.md",
            "<!-- c7: deterministic helpers, run as `python3 scripts/<name>.py`. "
            "Add one by emitting scripts/<name>.py. -->\n",
        ),
        (
            "sub_agents/README.md",
            "<!-- c5: delegated subagents, invoked with the Task tool in their OWN context. "
            "Add one as sub_agents/<name>/AGENT.md with a `description:` in its frontmatter. -->\n",
        ),
        (
            ".claude/skills/README.md",
            "<!-- c6: reusable workflows loaded on demand. Add one as "
            ".claude/skills/<name>/SKILL.md with frontmatter `name:` matching the directory "
            "and a `description:`. -->\n",
        ),
    ),
)

INSTALL_MODE = "claude_workspace"
HARNESS_DIR = ".claude/harness"
CLAUDE_MD = "CLAUDE.md"


def claude_md(surface: SurfaceSpec = CLAUDE_CODE_SURFACE) -> str:
    """The generated CLAUDE.md: one `@` import per always-on file, in surface order."""
    lines = ["<!-- generated by ClaudeCodeSubstrate.materialise; edit the harness tree -->"]
    lines += [f"@{HARNESS_DIR}/{rel}" for rel in surface.always_on]
    return "\n".join(lines) + "\n"


def _ensure_name(body: str, name: str) -> str:
    """Claude Code agents need `name:` in frontmatter; add it when the tree omits it."""
    if re.search(r"^name:\s*\S", body[:600], re.M):
        return body
    if body.startswith("---\n"):
        return f"---\nname: {name}\n" + body[4:]
    return f"---\nname: {name}\n---\n\n{body}"


class ClaudeCodeSubstrate:
    """Claude Code behind the one Substrate interface; the launcher body is benchmark-supplied."""

    name = "cc"

    def __init__(self, launcher: Launcher | None = None, *, cli: str = "claude"):
        self._launcher = launcher
        self._cli = cli

    def surface(self) -> SurfaceSpec:
        return CLAUDE_CODE_SURFACE

    def materialise(self, tree_dir: Path, spec, ctx: Mapping[str, str]) -> Install:
        mode = getattr(spec, "install_mode", INSTALL_MODE)
        if mode != INSTALL_MODE:
            raise ValueError(
                f"install_mode {mode!r} is not a Claude Code mode; this substrate supports "
                f"{INSTALL_MODE!r} only"
            )
        tree_dir = Path(tree_dir)
        if not HT.is_tree(CLAUDE_CODE_SURFACE, tree_dir):
            raise ValueError(f"{tree_dir} is not a harness tree (no always-on file present)")
        tree = HT.read_tree(CLAUDE_CODE_SURFACE, tree_dir)
        staged = Path(tempfile.mkdtemp(prefix="adapt-cc-"))
        try:
            for rel, body in tree.items():
                if rel in CLAUDE_CODE_SURFACE.always_on:
                    dest = staged / HARNESS_DIR / rel
                elif m := re.fullmatch(r"sub_agents/([^/]+)/AGENT\.md", rel):
                    dest = staged / ".claude" / "agents" / f"{m.group(1)}.md"
                    body = _ensure_name(body, m.group(1))
                else:
                    dest = staged / HT.normalize_rel(rel)
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(body, encoding="utf-8")
            for rel in CLAUDE_CODE_SURFACE.always_on:
                p = staged / HARNESS_DIR / rel
                if not p.exists():
                    p.parent.mkdir(parents=True, exist_ok=True)
                    p.write_text("", encoding="utf-8")
            (staged / CLAUDE_MD).write_text(claude_md(), encoding="utf-8")

            for key, body in ctx.items():
                if key.startswith("file:"):
                    p = staged / HT.normalize_rel(key[len("file:") :])
                    p.parent.mkdir(parents=True, exist_ok=True)
                    p.write_text(body, encoding="utf-8")
        except BaseException:
            shutil.rmtree(staged, ignore_errors=True)
            raise
        return Install(
            staging_dir=staged, fingerprint=RM.fingerprint(tree_dir), extras={"install_mode": mode}
        )

    def run_argv(self, prompt: str, model: str, *, max_turns: int) -> list[str]:
        """The reference argv for one headless rollout; launchers may build their own."""
        return [
            self._cli,
            "-p",
            prompt,
            "--model",
            model,
            "--output-format",
            "stream-json",
            "--verbose",
            "--max-turns",
            str(int(max_turns)),
            "--dangerously-skip-permissions",
        ]

    def execute(
        self, task_ref: str, install: Install, run_ids: list[str], timeout: int
    ) -> list[Path]:
        if self._launcher is None:
            raise RuntimeError(
                "ClaudeCodeSubstrate was constructed without a launcher body; the benchmark "
                "adapter must supply one (it owns runner choice, env wiring and read-back)"
            )
        return self._launcher(
            RunRequest(task_ref=task_ref, run_ids=tuple(run_ids), timeout=int(timeout)), install
        )

    def read_trajectory(
        self, stream_path: Path, *, obs_trunc: int, max_chars: int, args_trunc: int = 400
    ) -> str:
        return render_events(
            Path(stream_path), obs_trunc=obs_trunc, max_chars=max_chars, args_trunc=args_trunc
        )

    def preflight(self) -> None:
        """Checks the Claude Code CLI answers `--version`; starts no model call."""
        try:
            p = subprocess.run(
                [self._cli, "--version"], capture_output=True, text=True, timeout=60
            )
        except FileNotFoundError as e:
            raise RuntimeError(f"Claude Code CLI {self._cli!r} not found on PATH") from e
        if p.returncode != 0:
            raise RuntimeError(f"`{self._cli} --version` failed: {p.stderr.strip()[:300]}")


_TRUNC_FMT = "…(+{n} chars — render truncation)"


def _clip(s, n: int) -> str:
    s = "" if s is None else str(s)
    s = s.replace("\x00", "")
    if n <= 0 or len(s) <= n:
        return s
    return s[:n] + _TRUNC_FMT.format(n=len(s) - n)


def _result_text(content) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "\n".join(
            c.get("text", "") for c in content if isinstance(c, dict) and c.get("type") == "text"
        )
    return json.dumps(content, default=str)


def render_events(path: Path, *, obs_trunc: int, max_chars: int, args_trunc: int = 400) -> str:
    """Render Claude Code's `--output-format stream-json` JSONL into the shared grammar."""
    try:
        raw = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return f"(failed to read trajectory: {e})"
    lines: list[str] = []
    for ln in raw.splitlines():
        ln = ln.strip()
        if not ln.startswith("{"):
            continue
        try:
            ev = json.loads(ln)
        except json.JSONDecodeError:
            continue
        if not isinstance(ev, dict):
            continue
        kind = ev.get("type")
        content = (ev.get("message") or {}).get("content")
        if kind == "assistant" and isinstance(content, list):
            for part in content:
                if not isinstance(part, dict):
                    continue
                if part.get("type") == "text" and str(part.get("text", "")).strip():
                    lines.append(f"[ASSISTANT] {_clip(part['text'], obs_trunc)}")
                elif part.get("type") == "thinking" and str(part.get("thinking", "")).strip():
                    lines.append(f"[THINKING] {_clip(part['thinking'], obs_trunc)}")
                elif part.get("type") == "tool_use":
                    args = json.dumps(part.get("input"), default=str, ensure_ascii=False)
                    lines.append(f"[ACTION] {part.get('name', 'tool')}({_clip(args, args_trunc)})")
        elif kind == "user" and isinstance(content, list):
            for part in content:
                if isinstance(part, dict) and part.get("type") == "tool_result":
                    tag = "OBSERVATION ERROR" if part.get("is_error") else "OBSERVATION"
                    lines.append(f"[{tag}] {_clip(_result_text(part.get('content')), obs_trunc)}")
        elif kind == "result" and ev.get("subtype") not in (None, "success"):
            lines.append(f"[ERROR] {ev.get('subtype')}: {_clip(ev.get('result'), 300)}")
    rendered = "\n".join(lines).strip()
    if not rendered:
        return "(no parseable events in trajectory)"
    if len(rendered) > max_chars:
        dropped = len(rendered) - max_chars
        rendered = rendered[:max_chars] + "\n" + _TRUNC_FMT.format(n=dropped)
    return rendered
